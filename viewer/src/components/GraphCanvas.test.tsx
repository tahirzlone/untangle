  const twinned = fixture(
    {
      ...COLLIDING,
      suggestions: [
        COLLIDING.suggestions[0],
        { ...COLLIDING.suggestions[1], airtableRecordId: COLLIDING.suggestions[0].airtableRecordId },
      ],
    },
    'twinned',
  );
  render(<GraphCanvas workflow={twinned} />);

#!/usr/bin/env node
// Regenerates scripts/validate.bundle.mjs — the committed, dependency-free copy
// of the validator CLI that the skill runs where node_modules does not exist
// (a plugin-cache copy of this repo, or a fresh clone with no npm install).
//
// This wrapper exists instead of a one-line esbuild CLI invocation because the
// banner text carries spaces, backticks and an em dash; routing that through an
// npm script means cmd.exe on Windows and sh elsewhere, each mangling it its
// own way. esbuild's JS API takes the string verbatim on every platform.
//
// The bundle stays ESM so `import.meta.url` survives: validate-core.mjs reads
// the schema through `new URL('../schema/workflow.schema.json', import.meta.url)`,
// and from scripts/validate.bundle.mjs that still resolves to the one schema
// file on disk. The schema is deliberately NOT inlined — it is the contract,
// and it has exactly one source of truth.

import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';

const banner =
  '// GENERATED by `npm run bundle:validator` from scripts/validate.mjs — do not edit by hand.';

const root = new URL('../', import.meta.url);
const fromRoot = (p) => fileURLToPath(new URL(p, root));

await build({
  entryPoints: [fromRoot('scripts/validate.mjs')],
  outfile: fromRoot('scripts/validate.bundle.mjs'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  banner: { js: banner },
  // esbuild writes its module-path comments relative to absWorkingDir, which
  // otherwise defaults to process.cwd(). Every path above resolves from this
  // file's own URL, so the bundler runs from anywhere — and run from anywhere
  // else, it would stamp this checkout's directory name into ~1400 comment
  // lines and hand CI a 7800-line diff to explain. Pin it to the repo root.
  absWorkingDir: fileURLToPath(root),
});
